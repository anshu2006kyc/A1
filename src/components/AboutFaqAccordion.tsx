export const AboutFaqAccordion: React.FC = () => {
  const [openIds, setOpenIds] = useState<string[]>(['faq-1']);
  const [searchQuery, setSearchQuery] = useState('');
  const [activeCategory, setActiveCategory] = useState<'all' | 'investment' | 'payments' | 'security' | 'rewards'>('all');

  const toggleItem = (id: string) => {
    sfx.playTap();
    setOpenIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  const toggleAll = () => {
    sfx.playTap();
    if (openIds.length === filteredFaqs.length) {
      setOpenIds([]);
    } else {
      setOpenIds(filteredFaqs.map((f) => f.id));
    }
  };

  const filteredFaqs = useMemo(() => {
    return FAQ_DATA.filter((item) => {
      const matchesCategory = activeCategory === 'all' || item.category === activeCategory;
      const matchesSearch =
        searchQuery.trim() === '' ||
        item.question.toLowerCase().includes(searchQuery.toLowerCase()) ||
        item.answer.toLowerCase().includes(searchQuery.toLowerCase());
      return matchesCategory && matchesSearch;
    });
  }, [activeCategory, searchQuery]);

  return (
    <div className="bg-white p-5 rounded-3xl border border-gray-100 shadow-sm space-y-4">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div className="flex items-center space-x-2 text-xs font-bold text-emerald-700">
          <HelpCircle className="w-4 h-4 text-emerald-600" />
          <span className="uppercase tracking-wider">Frequently Asked Questions</span>
        </div>

        <button
          type="button"
          onClick={toggleAll}
          className="text-[10px] font-extrabold text-emerald-700 hover:text-emerald-800 bg-emerald-50 hover:bg-emerald-100 px-2.5 py-1 rounded-lg border border-emerald-200 transition-colors cursor-pointer"
        >
          {openIds.length === filteredFaqs.length ? 'Collapse All' : 'Expand All'}
        </button>
      </div>

      <p className="text-xs text-gray-500 font-normal">
        Clear answers to everything you need to know about investing, returns, recharges, and withdrawals with AKM Enterprises.
      </p>

      {/* Search Input */}
      <div className="relative">
        <Search className="w-4 h-4 text-gray-400 absolute left-3 top-1/2 -translate-y-1/2 pointer-events-none" />
        <input
          type="text"
          value={searchQuery}
          onChange={(e) => setSearchQuery(e.target.value)}
          placeholder="Search question (e.g. returns, withdrawal, turbo)..."
          className="w-full pl-9 pr-3 py-2 bg-gray-50 border border-gray-200 rounded-xl text-xs text-gray-800 focus:outline-none focus:border-emerald-500 focus:bg-white transition-all placeholder:text-gray-400"
        />
        {searchQuery && (
          <button
            onClick={() => setSearchQuery('')}
            className="absolute right-3 top-1/2 -translate-y-1/2 text-gray-400 hover:text-gray-600 text-xs font-bold"
          >
            Clear
          </button>
        )}
      </div>

      {/* Category Filter Chips */}
      <div className="flex space-x-1.5 overflow-x-auto scrollbar-none pb-0.5">
        {[
          { id: 'all', label: 'All FAQs' },
          { id: 'investment', label: 'Investments' },
          { id: 'payments', label: 'Recharge & Withdraw' },
          { id: 'security', label: 'Security' },
          { id: 'rewards', label: 'Lucky Spin & Streaks' }
        ].map((tab) => (
          <button
            key={tab.id}
            type="button"
            onClick={() => {
              sfx.playTap();
              setActiveCategory(tab.id as any);
            }}
            className={`px-3 py-1.5 rounded-xl text-[10.5px] font-bold whitespace-nowrap transition-all cursor-pointer ${
              activeCategory === tab.id
                ? 'bg-emerald-600 text-white shadow-xs font-black'
                : 'bg-gray-100 text-gray-600 hover:bg-gray-200'
            }`}
          >
            {tab.label}
          </button>
        ))}
      </div>

      {/* Collapsible Accordion Items */}
      <div className="space-y-2.5 pt-1">
        {filteredFaqs.map((faq) => {
          const isOpen = openIds.includes(faq.id);

          return (
            <div
              key={faq.id}
              className={`rounded-2xl border transition-all overflow-hidden ${
                isOpen
                  ? 'border-emerald-300/80 bg-emerald-50/20 shadow-xs'
                  : 'border-gray-100 bg-gray-50/60 hover:border-gray-200'
              }`}
            >
              {/* Question Header Button */}
              <button
                type="button"
                onClick={() => toggleItem(faq.id)}
                className="w-full p-3.5 flex items-center justify-between text-left cursor-pointer transition-colors"
              >
                <div className="flex items-center space-x-2.5 min-w-0 pr-2">
                  <span
                    className={`w-2 h-2 rounded-full shrink-0 ${
                      isOpen ? 'bg-emerald-500' : 'bg-gray-300'
                    }`}
                  />
                  <span className="text-xs font-bold text-gray-900 leading-snug">
                    {faq.question}
                  </span>
                </div>

                <div
                  className={`w-6 h-6 rounded-full flex items-center justify-center shrink-0 transition-transform duration-200 ${
                    isOpen ? 'rotate-180 bg-emerald-100 text-emerald-800' : 'bg-gray-200/80 text-gray-500'
                  }`}
                >
                  <ChevronDown className="w-3.5 h-3.5 stroke-[2.5]" />
                </div>
              </button>

              {/* Collapsible Answer Body */}
              {isOpen && (
                <div className="px-3.5 pb-3.5 pt-0 text-xs text-gray-700 leading-relaxed border-t border-emerald-100/60 animate-fade-in space-y-2 mt-1">
                  <div className="whitespace-pre-line font-normal text-gray-600 mt-2">
                    {faq.answer}
                  </div>

                  {faq.highlights && faq.highlights.length > 0 && (
                    <div className="pt-2 flex flex-wrap gap-1.5">
                      {faq.highlights.map((h, idx) => (
                        <div
                          key={`hl-${idx}`}
                          className="inline-flex items-center space-x-1 px-2 py-0.5 rounded-md bg-white border border-emerald-200 text-[9.5px] font-bold text-emerald-800 shadow-2xs"
                        >
                          <CheckCircle2 className="w-3 h-3 text-emerald-600 shrink-0" />
                          <span>{h}</span>
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              )}
            </div>
          );
        })}

        {filteredFaqs.length === 0 && (
          <div className="text-center py-6 text-gray-400 text-xs bg-gray-50 rounded-2xl p-4">
            No matching questions found for "{searchQuery}". Try another keyword or browse all categories.
          </div>
        )}
      </div>
    </div>
  );
};
